// Память в system prompt: как с ней работать и memo.md на начало сессии. Харнесс кладёт memo
// сам — модели не нужно тратить шаг на view, как предлагает протокол memory tool Anthropic;
// остальные файлы памяти она смотрит view, когда они нужны.

import { MEMO_PATH, MEMORY_ROOT } from './memoryPaths.js';

export function describeMemory(memo: string | null): string[] {
  return [
    '',
    `Память — папка ${MEMORY_ROOT}, тул memory. Она сохраняется между сессиями: записывай туда то, ` +
      'что пригодится потом, — договорённости с пользователем, его предпочтения, незаконченные дела. ' +
      `Главный файл — ${MEMO_PATH}: держи его коротким, актуальным и упорядоченным, лишнее удаляй. ` +
      'Новые файлы создавай, только если без них не обойтись.',
    memo === null || memo.trim() === ''
      ? `${MEMO_PATH} пока пуст.`
      : `${MEMO_PATH} на начало сессии:\n${memo.trim()}\n[Конец ${MEMO_PATH}]`,
  ];
}
