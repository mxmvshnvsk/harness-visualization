// Как читать карту смыслов: что такое PCA и UMAP, на бытовых примерах, и чего по карте
// утверждать нельзя. PCA — Карл Пирсон (1901) и Гарольд Хотеллинг (1933); UMAP — Лиланд
// Макиннес, Джон Хили, Джеймс Мелвилл (2018, https://arxiv.org/abs/1802.03426).

import type { ReactElement } from 'react';
import type { MapMethod } from './mapProjection';
import styles from './Data.module.css';

const METHODS: Record<
  MapMethod,
  { name: string; full: string; idea: string; example: string; trust: string; doubt: string }
> = {
  pca: {
    name: 'PCA',
    full: 'Principal Component Analysis — метод главных компонент',
    idea: 'Ищет два направления, вдоль которых точки разбросаны сильнее всего, и смотрит на облако точек вдоль них. Остальные 382 направления просто отбрасываются. Это линейная проекция: ничего не гнётся и не растягивается.',
    example:
      'Как тень от предмета на стене, если повернуть лампу так, чтобы тень вышла самой большой. По тени чайника видно, где носик и ручка, но два предмета, стоящие один за другим, на тени сольются.',
    trust:
      'Направления общие: если точки далеко по горизонтали, они правда различаются по самому заметному признаку базы. Одна и та же база всегда даёт одну и ту же карту.',
    doubt:
      'Близкие на карте могут быть далеки на самом деле — разница ушла в отброшенные направления. Поэтому темы часто слипаются в общую кучу.',
  },
  umap: {
    name: 'UMAP',
    full: 'Uniform Manifold Approximation and Projection — приближение и проекция многообразия',
    idea: 'Для каждой точки находит несколько ближайших соседей (здесь — 8) и раскладывает точки на плоскости так, чтобы соседи остались соседями. Как далеко лежат группы друг от друга — ему почти всё равно.',
    example:
      'Как схема метро: станции одной линии идут по порядку, пересадки на месте, но расстояния между районами нарисованы как удобно. По схеме видно, какие станции рядом, но не сколько идти пешком от одной окраины до другой.',
    trust:
      'Острова: документы одной темы собираются в кучки — так видно, какие темы в базе есть и какие фрагменты на них похожи.',
    doubt:
      'Расстояния между островами и размер острова ничего не значат. В алгоритме есть случайность — у нас seed зафиксирован, иначе карта менялась бы при каждом открытии.',
  },
};

export function MapExplainer({ method }: { method: MapMethod }): ReactElement {
  return (
    <details className={styles.explainer}>
      <summary>Как читать карту: что такое PCA и UMAP</summary>
      <p className={styles.note} data-teaching>
        У каждого фрагмента вектор из 384 чисел — точка в 384-мерном пространстве. Нарисовать его
        нельзя, поэтому карту сжимают до двух измерений. Сжатие всегда что-то теряет; два способа
        теряют разное. Переключайте PCA и UMAP наверху карты и сравнивайте.
      </p>
      <div className={styles.methods}>
        {(['pca', 'umap'] as const).map((key) => (
          <MethodCard key={key} method={METHODS[key]} active={method === key} />
        ))}
      </div>
      <p className={styles.note} data-teaching>
        <b>Общее правило:</b> карта — для того, чтобы увидеть форму базы, а не чтобы мерить. Какой
        фрагмент ближе к запросу, говорит косинус в списке справа: он считается по всем 384 числам,
        без сжатия. Попробуйте «удалёнка»: пунктир идёт к пяти ближайшим по косинусу — и на PCA
        часть из них лежит совсем не рядом со звездой.
      </p>
    </details>
  );
}

function MethodCard(props: { method: (typeof METHODS)[MapMethod]; active: boolean }): ReactElement {
  const { method } = props;
  return (
    <div className={styles.method} data-active={props.active ? 'true' : undefined}>
      <h4>
        {method.name}
        {props.active && <span className={styles.now}>сейчас на карте</span>}
      </h4>
      <p className={styles.full}>{method.full}</p>
      <p>{method.idea}</p>
      <p>
        <b>Пример.</b> {method.example}
      </p>
      <p>
        <b>Чему верить.</b> {method.trust}
      </p>
      <p>
        <b>Чему не верить.</b> {method.doubt}
      </p>
    </div>
  );
}
