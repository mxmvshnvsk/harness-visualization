// Вкладки трейса — те же значения, что у переключателя видов.
export type TourView = 'flow' | 'inspector' | 'code' | 'context' | 'rag' | 'mcp' | 'branches';

// Что подсветить: колонку «Диалог», плеер, открытую вкладку, во вкладке RAG — проверку опоры
// ответа или таблицу документов, или кнопку ветки шага.
export type TourTarget = 'dialog' | 'player' | 'view' | 'grounding' | 'documents' | 'branch';

// Что раскрыть во вкладке: запрос к модели или вызов тула — как переход по ссылке между видами.
export type TourFocus = { requestId: string } | { toolCallId: string };

// Элемент плеера, который «Попробуйте» просит нажать или потянуть: плеер поднимается над
// затемнением, элемент пульсирует рамкой. Иначе совет указывал бы в тёмную часть экрана.
export type TourControl = 'play' | 'strip';

export interface TourStop {
  view: TourView;
  // Номер события в трейсе (с нуля): плеер встаёт на его момент.
  at: number;
  target: TourTarget;
  also?: TourControl;
  focus?: TourFocus;
  title: string;
  text: string;
  look: string;
  tryThis: string;
}

