import type { UiMode } from './mode';
import type { LabName } from './useSelection';

export interface LabEntry {
  lab: LabName;
  title: string;
  // Коротко — для плитки на старте: «RAG», «Код-арена».
  name: string;
  // Плитка на старте в «Обучении»: о чём лаборатория, в несколько слов.
  hook: string;
  // Одна строка для коротких списков.
  short: string;
  // Та же строка в режиме «Исследование» — в терминах; нет — как в «Обучении».
  researchShort?: string;
  // Вопрос, на который отвечает лаборатория.
  question: string;
  // Что поймёте — для карточки на экране «Лаборатории».
  learn: string;
  minutes: number;
  // Нужен ли ключ модели.
  key: string;
  // Учебная лаборатория: в режиме «Исследование» её нет, остаются инструменты.
  teaching?: boolean;
}

