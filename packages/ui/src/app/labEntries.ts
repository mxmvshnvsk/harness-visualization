export function labEntries(mode: UiMode): readonly LabEntry[] {
  if (mode === 'learn') {
    return LAB_ENTRIES;
  }
  return LAB_ENTRIES.filter((entry) => entry.teaching !== true).map((entry) => ({
    ...entry,
    short: entry.researchShort ?? entry.short,
  }));
}
